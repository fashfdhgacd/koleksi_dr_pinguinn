import test from "node:test";
import assert from "node:assert/strict";
import { decodePublicPath, localeRewrites, localizedPath } from "../src/lib/public-locale.ts";

test("each public locale preserves watch IDs, queries and pagination", () => {
  for (const language of ["ms", "id", "en"]) {
    for (const path of ["/", "/watch/AbC-02", "/cari", "/kategori/jilbab/halaman/2", "/kontak"]) {
      const href = localizedPath(path + "?s=2#top", language);
      const url = new URL(href, "https://example.test");
      assert.deepEqual(decodePublicPath(url.pathname), { language, path });
      assert.equal(url.search + url.hash, "?s=2#top");
    }
    assert.equal(localizedPath("/pemilik", language), "/pemilik");
    assert.equal(localizedPath("/api/data", language), "/api/data");
  }
});

test("localized Indonesian categories keep /id on later pages", () => {
  for (const path of ["/kategori/malaysia", "/kategori/malaysia/halaman/5", "/kategori/videy/halaman/2", "/kategori/jav", "/kategori/hentai/halaman/3"]) {
    assert.equal(localizedPath(path, "id"), "/id" + path);
    assert.deepEqual(decodePublicPath("/id" + path), { language: "id", path });
    assert.equal(localizedPath(path, "ms"), "/ms" + path);
    assert.deepEqual(decodePublicPath("/ms" + path), { language: "ms", path });
  }
  assert.equal(localizedPath("/kategori/jilbab/halaman/2", "id"), "/kategori/jilbab/halaman/2");
  assert.notEqual(decodePublicPath("/id/kategori/jilbab/halaman/2").path, "/kategori/jilbab/halaman/2");
});

test("existing English collection and its translations resolve to the same loader", () => {
  const path = "/en/indo-viral/halaman/2";
  for (const language of ["ms", "id", "en"]) {
    assert.deepEqual(decodePublicPath(localizedPath(path, language)), { language, path });
  }
});

test("one request's language cannot change links generated by another router", () => {
  const first = localeRewrites(), second = localeRewrites();
  const make = path => new URL(path, "https://example.test");
  first.input({ url: make("/ms/kontak") });
  second.input({ url: make("/en/kontak") });
  assert.equal(first.output({ url: make("/watch/Test") }).pathname, "/ms/watch/Test");
  assert.equal(second.output({ url: make("/watch/Test") }).pathname, "/en/watch/Test");
});
