function toPath(rows: string[], ch: string): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === ch) {
        let w = 1;
        while (row[x + w] === ch) w++;
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      } else x++;
    }
  });
  return d;
}

export function PixelIcon({ slug, className }: { slug: string; className?: string }) {
  const rows = ICONS[SLUG_ICON[slug] || "tag"] || ICONS.tag;
  const white = toPath(rows, "#");
  const red = toPath(rows, "r");
  return (
    <svg
      viewBox="0 0 16 16"
      width={48}
      height={48}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path d={white} fill="#f5f5f5" />
      {red ? <path d={red} fill="#e5484d" /> : null}
    </svg>
  );
}

