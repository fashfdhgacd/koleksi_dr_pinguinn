function toPath(rows: string[], ch: string): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === ch) {
        let w = 1;
        while (row[x + w] === ch) w++;
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      } else x++;
    }
  });
  return d;
}

const PATHS = new Map<string, { white: string; red: string }>();
function pathsFor(name: string): { white: string; red: string } {
  let hit = PATHS.get(name);
  if (!hit) {
    const rows = ICONS[name] || ICONS.tag;
    hit = { white: toPath(rows, "#"), red: toPath(rows, "r") };
    PATHS.set(name, hit);
  }
  return hit;
}

/** 32x32 grid drawn at 64x64 CSS px (exact 2x; 4x/6x device px on 2x/3x screens). */
export function PixelIcon({ slug, className }: { slug: string; className?: string }) {
  const { white, red } = pathsFor(SLUG_ICON[slug] || "tag");
  return (
    <svg
      viewBox="0 0 32 32"
      width={64}
      height={64}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
      style={{ width: 64, height: 64, flex: "none" }}
    >
      <path d={white} fill="#f5f5f5" />
      {red ? <path d={red} fill="#e5484d" /> : null}
    </svg>
  );
}

